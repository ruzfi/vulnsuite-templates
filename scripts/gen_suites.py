#!/usr/bin/env python3
"""Generate SUITES.md from every suite file in suites/.

A suite is a named list of selectors (ids, group handles, categories, nested
`suite:` refs, or filter lines) that vulnsuite stands up in one run; the format
is documented in schemas/suite-format.md. SUITES.md is a derived index: it is
regenerated from the suite files and the contracts, and must never be hand-edited.
CI runs this with --check and fails if SUITES.md is stale, so the single source of
truth stays the suite files plus each contract.yaml.

    python3 scripts/gen_suites.py            # rewrite SUITES.md
    python3 scripts/gen_suites.py --check    # exit 1 if SUITES.md is out of date

Besides rendering, this resolves every selector and errors on a line that matches
nothing, an unknown nested suite, or a cycle — so it doubles as a suite linter.

Requires PyYAML (pip install pyyaml).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SUITES_DIR = ROOT / "suites"
SUITES_MD = ROOT / "SUITES.md"
KEV_FILE = ROOT / "data" / "cisa-kev.txt"
HEADER = "<!-- GENERATED by scripts/gen_suites.py from suites/*.txt and each contract.yaml — do not edit by hand. -->"


def load_kev() -> set[str]:
    if not KEV_FILE.exists():
        return set()
    return {
        ln.strip()
        for ln in KEV_FILE.read_text().splitlines()
        if ln.strip() and not ln.startswith("#")
    }


class Target:
    __slots__ = ("id", "category", "meta", "kev")

    def __init__(self, path: Path, kev: set[str]):
        data = yaml.safe_load(path.read_text()) or {}
        self.meta = data.get("metadata", {}) or {}
        self.id = self.meta.get("id", path.parent.name)
        self.category = path.parent.parent.name
        refs = self.meta.get("vuln_refs", []) or []
        self.kev = bool(kev) and any(r in kev for r in refs if r.startswith("CVE-"))

    @property
    def group(self):
        return self.meta.get("group")

    @property
    def primary(self):
        return bool(self.meta.get("primary", False))

    @property
    def variant(self):
        return self.meta.get("variant")


def load_targets() -> list[Target]:
    kev = load_kev()
    paths = sorted(
        p for p in ROOT.glob("*/*/contract.yaml") if ".git" not in p.parts
    )
    return [Target(p, kev) for p in paths]


# --- filter predicates (mirror `vulnsuite list` semantics) --------------------

def _match_filter(t: Target, tokens: list[str]) -> bool:
    """A filter line is a list of -flag [value] tokens that AND together."""
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        val = tokens[i + 1] if i + 1 < len(tokens) else None

        def classes():
            return t.meta.get("class", []) or []

        if tok in ("-class",):
            if val not in classes():
                return False
            i += 2
        elif tok in ("-tag",):
            if val not in (t.meta.get("tags", []) or []):
                return False
            i += 2
        elif tok in ("-category", "-product"):
            if t.category != val:
                return False
            i += 2
        elif tok in ("-fidelity",):
            if t.meta.get("fidelity") != val:
                return False
            i += 2
        elif tok in ("-ref",):
            if val not in (t.meta.get("vuln_refs", []) or []):
                return False
            i += 2
        elif tok in ("-year",):
            refs = t.meta.get("vuln_refs", []) or []
            disclosed = t.meta.get("disclosed", "")
            yr = disclosed[:4] if disclosed else ""
            years = {r.split("-")[1] for r in refs if r.startswith("CVE-")}
            if yr:
                years.add(yr)
            if val not in years:
                return False
            i += 2
        elif tok == "-cve":
            if not any(r.startswith("CVE-") for r in t.meta.get("vuln_refs", []) or []):
                return False
            i += 1
        elif tok == "-no-cve":
            if any(r.startswith("CVE-") for r in t.meta.get("vuln_refs", []) or []):
                return False
            i += 1
        elif tok == "-kev":
            if not t.kev:
                return False
            i += 1
        elif tok == "-no-kev":
            if t.kev:
                return False
            i += 1
        else:
            raise ValueError(f"unknown filter token: {tok}")
    return True


# --- suite parsing + resolution ----------------------------------------------

def read_suite(name: str) -> tuple[str, list[str]]:
    """Return (description, selector-lines) for suite <name>."""
    path = SUITES_DIR / f"{name}.txt"
    if not path.exists():
        raise ValueError(f"unknown suite: suite:{name} ({path} not found)")
    desc_lines: list[str] = []
    selectors: list[str] = []
    seen_selector = False
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if not seen_selector:
                desc_lines.append(line.lstrip("#").strip())
            continue
        seen_selector = True
        selectors.append(line)
    return " ".join(desc_lines), selectors


def resolve_selector(
    sel: str,
    targets: list[Target],
    by_id: dict,
    groups: dict,
    categories: set,
    stack: tuple,
) -> list[tuple[Target, str, bool]]:
    """Resolve one selector line to [(target, via, in_default)].

    `via` is a human label for how the target was selected; `in_default` is False
    only for a non-primary group member reached through a bare group handle (it
    joins the run only under -variants).
    """
    if sel.startswith("suite:"):
        name = sel[len("suite:"):]
        if name in stack:
            raise ValueError(f"suite cycle: {' -> '.join(stack + (name,))}")
        _, nested = read_suite(name)
        out: list[tuple[Target, str, bool]] = []
        for s in nested:
            out += resolve_selector(s, targets, by_id, groups, categories, stack + (name,))
        return out
    if sel.startswith("-"):
        tokens = sel.split()
        matched = [t for t in targets if _match_filter(t, tokens)]
        if not matched:
            raise ValueError(f"filter line matches no target: {sel!r}")
        return [(t, sel, True) for t in matched]
    # bare selector: exact id -> exact group -> category -> unique substring
    if sel in by_id:
        return [(by_id[sel], "id", True)]
    if sel in groups:
        members = groups[sel]
        return [(t, f"`{sel}`", t.primary) for t in members]
    if sel in categories:
        return [(t, f"category `{sel}`", True) for t in targets if t.category == sel]
    hits = [t for t in targets if sel in t.id]
    if len(hits) == 1:
        return [(hits[0], f"~{sel}", True)]
    if not hits:
        raise ValueError(f"selector resolves to no target: {sel!r}")
    raise ValueError(f"selector {sel!r} is an ambiguous substring ({len(hits)} matches)")


def resolve_suite(name, targets, by_id, groups, categories):
    desc, selectors = read_suite(name)
    rows: list[tuple[Target, str, bool]] = []
    seen: dict[str, tuple] = {}
    for sel in selectors:
        for t, via, in_default in resolve_selector(sel, targets, by_id, groups, categories, (name,)):
            if t.id in seen:
                # keep the first via; promote in_default if any path includes it by default
                prev_t, prev_via, prev_def = seen[t.id]
                if in_default and not prev_def:
                    seen[t.id] = (prev_t, prev_via, True)
                continue
            seen[t.id] = (t, via, in_default)
            rows.append((t, via, in_default))
    # re-read promoted in_default flags, preserve first-seen order
    rows = [(t, seen[t.id][1], seen[t.id][2]) for (t, _, _) in rows]
    return desc, selectors, rows


def render() -> str:
    targets = load_targets()
    by_id = {t.id: t for t in targets}
    categories = {t.category for t in targets}
    groups: dict[str, list[Target]] = {}
    for t in targets:
        if t.group:
            groups.setdefault(t.group, []).append(t)
    for g in groups:
        groups[g].sort(key=lambda t: (not t.primary, t.variant or "", t.id))

    names = sorted(p.stem for p in SUITES_DIR.glob("*.txt"))
    lines = [
        HEADER,
        "",
        "# Suites",
        "",
        f"{len(names)} suite(s). Regenerate with `python3 scripts/gen_suites.py`.",
        "",
        "A suite is a named list of selectors stood up in one run; the format is "
        "[schemas/suite-format.md](schemas/suite-format.md). Reference one from the "
        "CLI with the explicit `suite:` prefix:",
        "",
        "```bash",
        "vulnsuite run -t suite:<name>              # the suite's default set",
        "vulnsuite run -t suite:<name> -variants    # expand every group member",
        "```",
        "",
        "Per suite below: **Default** is the set a bare `suite:<name>` stands up; a "
        "group handle contributes its primary (★) by default and the rest "
        "(`-variants` only) are listed too. Suites carry no CVE facts — they "
        "reference targets by selector only.",
        "",
    ]
    for name in names:
        desc, selectors, rows = resolve_suite(name, targets, by_id, groups, categories)
        default_n = sum(1 for _, _, d in rows if d)
        lines += [
            f"## `{name}`",
            "",
            desc or "_(no description)_",
            "",
            f"Selectors: {', '.join(f'`{s}`' for s in selectors)}",
            "",
            f"Members: **{default_n}** default, **{len(rows)}** with `-variants`.",
            "",
            "| Target | Category | Via | Default |",
            "| --- | --- | --- | --- |",
        ]
        for t, via, in_default in rows:
            star = " ★" if (t.group and t.primary and via.startswith("`")) else ""
            mark = "✓" if in_default else "`-variants`"
            lines.append(f"| `{t.id}` | {t.category} | {via}{star} | {mark} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    try:
        content = render()
    except ValueError as e:
        print(f"suite error: {e}", file=sys.stderr)
        return 1
    if "--check" in sys.argv[1:]:
        current = SUITES_MD.read_text() if SUITES_MD.exists() else ""
        if current != content:
            print("SUITES.md is out of date; run: python3 scripts/gen_suites.py", file=sys.stderr)
            return 1
        print("SUITES.md is up to date.")
        return 0
    SUITES_MD.write_text(content)
    print(f"Wrote {SUITES_MD.relative_to(ROOT)} ({content.count(chr(10))} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
