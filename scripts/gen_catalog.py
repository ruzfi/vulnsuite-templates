#!/usr/bin/env python3
"""Generate CATALOG.md from every contract.yaml in the repo.

The catalog is a derived index: it is regenerated from the contracts and must
never be hand-edited. CI runs this with --check and fails if CATALOG.md is stale,
so the single source of truth for every target stays its contract.yaml.

    python3 scripts/gen_catalog.py            # rewrite CATALOG.md
    python3 scripts/gen_catalog.py --check    # exit 1 if CATALOG.md is out of date

Requires PyYAML (pip install pyyaml).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "CATALOG.md"
HEADER = "<!-- GENERATED by scripts/gen_catalog.py from each contract.yaml — do not edit by hand. -->"


def find_contracts() -> list[Path]:
    return sorted(
        p for p in ROOT.glob("*/*/contract.yaml") if ".git" not in p.parts
    )


def row(path: Path) -> tuple[str, str, str]:
    """Return (category, id, markdown-row) for one contract."""
    data = yaml.safe_load(path.read_text()) or {}
    meta = data.get("metadata", {}) or {}
    category = path.parent.parent.name
    tid = meta.get("id", path.parent.name)
    cves = ", ".join(meta.get("vuln_refs", [])) or "—"
    severity = meta.get("severity", "—")
    fidelity = meta.get("fidelity", "—")
    detection = meta.get("detection", "unset")
    updated = meta.get("updated") or meta.get("added", "—")
    cell = f"| `{tid}` | {category} | {cves} | {severity} | {fidelity} | {detection} | {updated} |"
    return category, tid, cell


def render() -> str:
    rows = sorted((row(p) for p in find_contracts()), key=lambda r: (r[0], r[1]))
    lines = [
        HEADER,
        "",
        "# Catalog",
        "",
        f"{len(rows)} target(s). Regenerate with `python3 scripts/gen_catalog.py`.",
        "",
        "| Target | Category | CVEs | Severity | Fidelity | Detection | Updated |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *[cell for _, _, cell in rows],
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    content = render()
    check = "--check" in sys.argv[1:]
    if check:
        current = CATALOG.read_text() if CATALOG.exists() else ""
        if current != content:
            print("CATALOG.md is out of date; run: python3 scripts/gen_catalog.py", file=sys.stderr)
            return 1
        print("CATALOG.md is up to date.")
        return 0
    CATALOG.write_text(content)
    print(f"Wrote {CATALOG.relative_to(ROOT)} ({content.count(chr(10))} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
