#!/usr/bin/env python3
"""Generate CATALOG.md from every contract.yaml in the repo.

The catalog is a derived index: it is regenerated from the contracts and must
never be hand-edited. CI runs this with --check and fails if CATALOG.md is stale,
so the single source of truth for every target stays its contract.yaml.

    python3 scripts/gen_catalog.py            # rewrite CATALOG.md
    python3 scripts/gen_catalog.py --check    # exit 1 if CATALOG.md is out of date

Requires PyYAML (pip install pyyaml).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "CATALOG.md"
KEV_FILE = ROOT / "data" / "cisa-kev.txt"
HEADER = "<!-- GENERATED by scripts/gen_catalog.py from each contract.yaml — do not edit by hand. -->"


def load_kev() -> set[str]:
    """CVE ids on the CISA KEV catalog, from data/cisa-kev.txt (kept fresh by
    the cisa-kev-sync workflow). Empty set if the file is absent/unsynced."""
    if not KEV_FILE.exists():
        return set()
    return {
        ln.strip()
        for ln in KEV_FILE.read_text().splitlines()
        if ln.strip() and not ln.startswith("#")
    }


def find_contracts() -> list[Path]:
    return sorted(
        p for p in ROOT.glob("*/*/contract.yaml") if ".git" not in p.parts
    )


def row(path: Path, kev: set[str]) -> tuple[tuple, str]:
    """Return (sort_key, markdown-row) for one contract.

    The sort key clusters variant-group members together (primary first),
    while ungrouped targets sort by id within their category, so members of a
    group render as a contiguous block under their group handle.
    """
    data = yaml.safe_load(path.read_text()) or {}
    meta = data.get("metadata", {}) or {}
    category = path.parent.parent.name
    tid = meta.get("id", path.parent.name)
    group = meta.get("group")
    variant = meta.get("variant")
    primary = bool(meta.get("primary", False))
    refs = meta.get("vuln_refs", []) or []
    cves = ", ".join(refs) or "—"
    classes = ", ".join(meta.get("class", [])) or "—"
    # KEV is DERIVED: any CVE in vuln_refs that is on the CISA KEV catalog.
    cve_ids = [r for r in refs if r.startswith("CVE-")]
    if not kev:
        kev_cell = "?"  # catalog not synced yet
    elif any(r in kev for r in cve_ids):
        kev_cell = "**yes**"
    else:
        kev_cell = "no"
    severity = meta.get("severity", "—")
    fidelity = meta.get("fidelity", "—")
    detection = meta.get("detection", "unset")
    updated = meta.get("updated") or meta.get("added", "—")
    # Group cell: `handle` · variant, with ★ marking the group's primary member.
    if group:
        group_cell = f"`{group}`"
        if variant:
            group_cell += f" · {variant}"
        if primary:
            group_cell += " ★"
    else:
        group_cell = "—"
    cell = (
        f"| `{tid}` | {category} | {group_cell} | {classes} | {cves} | {kev_cell} | "
        f"{severity} | {fidelity} | {detection} | {updated} |"
    )
    # Cluster grouped members together (by group handle), ungrouped by id;
    # within a group the primary sorts first, then variants alphabetically.
    cluster = group or tid
    sort_key = (category, cluster, 0 if primary else 1, variant or "", tid)
    return sort_key, cell


def render() -> str:
    kev = load_kev()
    rows = sorted((row(p, kev) for p in find_contracts()), key=lambda r: r[0])
    kev_note = (
        "KEV is derived from `data/cisa-kev.txt` (CISA Known Exploited "
        "Vulnerabilities), refreshed by the cisa-kev-sync workflow; `?` means "
        "the catalog has not been synced yet."
    )
    group_note = (
        "Group is the variant-family handle (`metadata.group`); members of a "
        "group render together, and ★ marks the group's primary member — the "
        "one a bare `-t <group>` selector resolves to."
    )
    lines = [
        HEADER,
        "",
        "# Catalog",
        "",
        f"{len(rows)} target(s). Regenerate with `python3 scripts/gen_catalog.py`.",
        "",
        kev_note,
        "",
        group_note,
        "",
        "| Target | Category | Group | Class | CVEs | KEV | Severity | Fidelity | Detection | Updated |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        *[cell for _, cell in rows],
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    content = render()
    check = "--check" in sys.argv[1:]
    if check:
        current = CATALOG.read_text() if CATALOG.exists() else ""
        if current != content:
            print("CATALOG.md is out of date; run: python3 scripts/gen_catalog.py", file=sys.stderr)
            return 1
        print("CATALOG.md is up to date.")
        return 0
    CATALOG.write_text(content)
    print(f"Wrote {CATALOG.relative_to(ROOT)} ({content.count(chr(10))} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
