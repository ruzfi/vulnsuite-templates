#!/usr/bin/env python3
"""Refresh data/cisa-kev.txt from the CISA Known Exploited Vulnerabilities feed.

Writes the sorted, unique CVE ids (plus a provenance header) that gen_catalog.py
reads to derive the KEV column. Run by .github/workflows/cisa-kev-sync.yml on a
schedule; safe to run locally too. Stdlib only — no third-party deps.

    python3 scripts/fetch_kev.py            # rewrite data/cisa-kev.txt
    python3 scripts/fetch_kev.py --check    # exit 1 if it would change
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

FEED = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json"
OUT = Path(__file__).resolve().parent.parent / "data" / "cisa-kev.txt"


def build() -> str:
    with urllib.request.urlopen(FEED, timeout=60) as resp:
        data = json.load(resp)
    cves = sorted({v["cveID"] for v in data.get("vulnerabilities", []) if v.get("cveID")})
    header = (
        "# CISA Known Exploited Vulnerabilities — CVE ids only.\n"
        f"# Source: {FEED}\n"
        f"# catalogVersion: {data.get('catalogVersion')}  count: {data.get('count')}\n"
        "# Regenerated by .github/workflows/cisa-kev-sync.yml — do not edit by hand.\n"
    )
    return header + "\n".join(cves) + "\n"


def main() -> int:
    content = build()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text() if OUT.exists() else ""
        if current != content:
            print("data/cisa-kev.txt is out of date; run: python3 scripts/fetch_kev.py", file=sys.stderr)
            return 1
        print("data/cisa-kev.txt is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content)
    print(f"Wrote {OUT.name} ({content.count(chr(10)) - 4} CVE ids).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
